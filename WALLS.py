def check_bounds_match_grid(grid, bounds):
    cov = np.zeros_like(grid, dtype=np.int32)
    for r0, c0, r1, c1 in bounds:
        cov[r0:r1, c0:c1] = 1

    missing = np.argwhere((grid == 1) & (cov == 0))
    extra   = np.argwhere((grid == 0) & (cov == 1))

    return missing, extra

